const used = JA.flatMap(([ids]) => ids);
if (used.length !== en.length || used.some((n, i) => n !== i + 1)) throw new Error("cue mapping does not cover every English cue once, in order");

const out = JA.map(([ids, text], i) => `${i + 1}\n${en[ids[0] - 1].start} --> ${en[ids.at(-1) - 1].end}\n${text}\n`).join("\n");
fs.writeFileSync("out/hanko-demo.ja.srt", out);
