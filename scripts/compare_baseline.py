"""Retrospective paired comparison on recorded live decisions. No network calls.

Run from the repository root: python scripts/compare_baseline.py
This studies entry selection, not a tradable portfolio or echo-only ablation.
"""
import hashlib
import json
from datetime import datetime
from pathlib import Path


def at(value):
    return datetime.fromisoformat(value.replace("Z", "+00:00"))


def baseline_enters(record):
    readings = record["readings"]
    bull = sum(r["conviction"] for r in readings if r["stance"] == "bullish")
    bear = sum(r["conviction"] for r in readings if r["stance"] == "bearish")
    return record["convergence"]["distinct_authors"] >= 2 and bull > bear


def endpoint(record, review):
    c = record["commitment"]
    samples = [s for s in review["observations"]["samples"]
               if at(c["decided_at"]) < at(s["at"]) <= at(c["review_at"])
               and s["metrics"].get("price_usd") is not None
               and s["metrics"]["price_usd"] > 0]
    entry = record["market"].get("price_usd")
    if not entry or entry <= 0 or not samples:
        return None
    last = max(samples, key=lambda s: at(s["at"]))
    # Refuse to represent a very old reading as the 72h endpoint.
    lag = (at(c["review_at"]) - at(last["at"])).total_seconds() / 3600
    if lag > 6:
        return None
    return last["metrics"]["price_usd"] / entry - 1, last["at"], lag


def compare(decisions, reviews):
    by_id = {r["decision_id"]: r for r in reviews if not r.get("early")}
    rows = []
    excluded = {"unreviewed_or_early": 0, "missing_or_stale_endpoint": 0}
    for d in decisions:
        review = by_id.get(d["decision_id"])
        if review is None:
            excluded["unreviewed_or_early"] += 1
            continue
        observed = endpoint(d, review)
        if observed is None:
            excluded["missing_or_stale_endpoint"] += 1
            continue
        ret, stamp, lag = observed
        rows.append({"decision_id": d["decision_id"], "subject": d["commitment"]["subject"],
                     "hanko_enter": d["commitment"]["verdict"] == "enter",
                     "baseline_enter": baseline_enters(d), "price_return": ret,
                     "endpoint_at": stamp, "endpoint_lag_hours": lag})
    strategies = {}
    for name in ("hanko", "baseline"):
        entered = [r for r in rows if r[name + "_enter"]]
        strategies[name] = {"entries": len(entered),
                            "mean_entered_return": sum(r["price_return"] for r in entered) / len(entered) if entered else None,
                            "positive_entries": sum(r["price_return"] > 0 for r in entered),
                            "mean_opportunity_contribution": sum(r["price_return"] * 0.01 for r in entered) / len(rows) if rows else None}
    return {"eligible": len(rows), "excluded": excluded, "strategies": strategies,
            "disagreements": sum(r["hanko_enter"] != r["baseline_enter"] for r in rows), "rows": rows}


def main():
    paths = [Path("live/decisions.jsonl"), Path("live/reviews.jsonl")]
    records = [[json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()] for p in paths]
    result = compare(*records)
    result["inputs"] = {str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in paths}
    out = Path("study/baseline")
    out.mkdir(parents=True, exist_ok=True)
    (out / "results.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    lines = ["# Retrospective entry-selection comparison", "",
             "Generated by `python scripts/compare_baseline.py` from committed live records. Input SHA-256 digests and every included decision are in `results.json`.", "",
             "The baseline enters when bullish conviction exceeds bearish conviction and at least two distinct authors mention the token. It uses the exact recorded readings, before independence filtering. It ignores Hanko's quality, conviction, safety and exit gates. This compares the complete selection rule; it does not isolate the effect of echo detection.", "",
             "Only non-early reviewed decisions with a positive entry price and a positive observed endpoint inside the original window, no more than six hours before its deadline, qualify. Both strategies use the same endpoint and opportunities. Refusals contribute zero. Each entry is assigned an equal hypothetical 1% position to isolate selection from sizing. Fees, spread and execution impact are omitted. No portfolio is simulated; overlapping windows and correlated tokens make these observations dependent.", "",
             f"Eligible opportunities: {result['eligible']}. Different entry choices: {result['disagreements']}. Exclusions: {result['excluded']}.", "",
             "| Rule | Entries | Positive returns | Mean price return on entries | Mean contribution per opportunity at 1% size |",
             "|---|---:|---:|---:|---:|"]
    def pct(v):
        return "unavailable" if v is None else f"{v * 100:+.4f}%"
    for name, s in result["strategies"].items():
        lines.append(f"| {name} | {s['entries']} | {s['positive_entries']} | {pct(s['mean_entered_return'])} | {pct(s['mean_opportunity_contribution'])} |")
    lines += ["", "This baseline and endpoint filter were specified after inspecting the project's live record. This is exploratory, retrospective evidence, not a preregistered test, profitability claim, or estimate of future performance. A held falsifier is a different outcome from a positive price return. More history and a prospective comparison are needed before asserting an advantage.", ""]
    (out / "README.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
